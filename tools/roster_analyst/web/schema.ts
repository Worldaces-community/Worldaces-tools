/**
 * Model of the params.json edited in the browser: default profile, merge of an
 * imported file, help texts. The lists (stats, traits, signs, default
 * settings) come from the engine → a single source of truth.
 */

import { ALL_STATS, ALL_TRAITS } from "../src/config/constants";
import { ALL_SIGNS, LIBERO_SIGN_EFFECT } from "../src/config/signs";
import { DEFAULT_SETTINGS, Settings } from "../src/config/settings";
import type { RoleName, Sign } from "../src/types";
import starter from "../example_params.json";

export const ROLES: RoleName[] = ["setter", "outsideHitter", "middleBlocker", "oppositeHitter", "libero"];

export const ROLE_TITLES: Record<RoleName, string> = {
    setter: "Setter",
    outsideHitter: "Outside Hitter",
    middleBlocker: "Middle Blocker",
    oppositeHitter: "Opposite",
    libero: "Libero",
};

export interface RoleParams {
    statsWeights: Record<string, number>;
    traitBonuses: Record<string, number>;
    /** Empty for the setter (no sign effect to activate). */
    signBonuses: Record<string, number>;
    /** Setter only: points per connected attacker. */
    connectionBonus?: number;
}

export interface EditableParams {
    _comment?: string;
    traitWeight: number;
    signWeight: number;
    settings: Settings;
    roles: Record<RoleName, RoleParams>;
}

export const STATS = ALL_STATS;
export const TRAITS = ALL_TRAITS;
export const SIGNS = ALL_SIGNS as string[];

/** Ranges of the editor controls. */
export const RANGES = {
    stat: { min: 0, max: 10, step: 1 },
    trait: { min: -10, max: 10, step: 0.5 },
    sign: { min: 0, max: 10, step: 0.5 },
    connection: { min: 0, max: 10, step: 0.5 },
};

const COMMENT =
    "World Aces roster analyst parameters — generated by the web editor. " +
    "statsWeights: 0-10 per sub-stat (normalised, only ratios matter). " +
    "traitBonuses / signBonuses: points added to the 0-99 stat score (a sign bonus only counts when the sign effect is active). " +
    "setter.connectionBonus: points per attacker connected with the setter. " +
    "traitWeight multiplies every traitBonus, signWeight every signBonus and the connectionBonus. settings: thresholds of the analysis.";

const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v)) as T;

/**
 * Base of an import: every stat counts the same, no trait / sign bonus, so a
 * value missing from the imported file counts for nothing.
 */
function neutralParams(): EditableParams {
    const roles = {} as Record<RoleName, RoleParams>;
    for (const r of ROLES) {
        roles[r] = {
            statsWeights: Object.fromEntries(STATS.map((s) => [s, 5])),
            traitBonuses: Object.fromEntries(TRAITS.map((t) => [t, 0])),
            // The setter activates no sign effect: only the connection is rated.
            signBonuses: r === "setter" ? {} : Object.fromEntries(SIGNS.map((s) => [s, 0])),
            ...(r === "setter" ? { connectionBonus: 0 } : {}),
        };
    }
    return { _comment: COMMENT, traitWeight: 1, signWeight: 1, settings: clone(DEFAULT_SETTINGS), roles };
}

/**
 * Default profile (example_params.json): every stat, trait and sign rated on 3
 * levels — 2 minor, 5 useful, 8 key (0 = cannot trigger in the role). A
 * coherent first take to show what the tool does, not a tuned profile.
 */
export function defaultParams(): EditableParams {
    return importParams(starter).params;
}

const isObj = (v: unknown): v is Record<string, unknown> =>
    typeof v === "object" && v !== null && !Array.isArray(v);

/** Deep merge of known keys only (same type as the template). */
function mergeKnown(base: Record<string, unknown>, src: unknown, freeKeys: Set<string>, path = "", notes: string[] = []): string[] {
    if (!isObj(src)) return notes;
    for (const [k, v] of Object.entries(src)) {
        const p = path ? `${path}.${k}` : k;
        if (k.startsWith("_")) continue;
        if (!(k in base)) { notes.push(`unknown key "${p}" ignored`); continue; }
        const cur = base[k];
        if (freeKeys.has(p)) {
            if (isObj(v)) base[k] = clone(v);
        } else if (isObj(cur)) {
            mergeKnown(cur, v, freeKeys, p, notes);
        } else if (Array.isArray(cur)) {
            if (Array.isArray(v)) base[k] = clone(v);
            else notes.push(`"${p}" should be a list — default kept`);
        } else if (typeof v === typeof cur) {
            base[k] = v;
        } else {
            notes.push(`"${p}" should be a ${typeof cur} — default kept`);
        }
    }
    return notes;
}

/**
 * Loads an existing params.json on top of the neutral template. Missing values
 * keep their neutral default; unknown keys are reported.
 */
export function importParams(raw: unknown): { params: EditableParams; notes: string[] } {
    if (!isObj(raw)) throw new Error("not a JSON object");
    if (!isObj(raw.roles)) throw new Error('missing "roles" block');
    const p = neutralParams();
    const notes: string[] = [];
    if (typeof raw.traitWeight === "number") p.traitWeight = raw.traitWeight;
    if (typeof raw.signWeight === "number") p.signWeight = raw.signWeight;
    // Older files rated the setter's signs: no sign effect to activate → dropped.
    let roles = raw.roles;
    if (isObj(roles.setter) && isObj(roles.setter.signBonuses)) {
        const { signBonuses, ...rest } = roles.setter;
        if (Object.values(signBonuses).some((v) => v !== 0)) {
            notes.push("roles.setter.signBonuses ignored: the setter activates no sign effect (rate the connection instead)");
        }
        roles = { ...roles, setter: rest };
    }
    mergeKnown(p.settings as unknown as Record<string, unknown>, raw.settings, new Set([
        "settings.roster.targetCounts", "settings.recruitment.singletonTraitPositions",
    ]), "settings", notes);
    for (const [role, cfg] of Object.entries(roles)) {
        if (!(ROLES as string[]).includes(role)) { notes.push(`unknown role "${role}" ignored`); continue; }
        mergeKnown(p.roles[role as RoleName] as unknown as Record<string, unknown>, cfg, new Set(), `roles.${role}`, notes);
    }
    // The editor rates the libero's signs per effect: a group rated unevenly
    // in the file is aligned on its highest rating.
    const libero = p.roles.libero.signBonuses;
    for (const g of LIBERO_SIGN_GROUPS) {
        const vals = g.signs.map((s) => libero[s] ?? 0);
        if (vals.some((v) => v !== vals[0])) {
            const max = Math.max(...vals);
            for (const s of g.signs) libero[s] = max;
            notes.push(`libero signs ${g.signs.join(", ")} share the "${g.effect}" effect: all set to ${max}`);
        }
    }
    return { params: p, notes };
}

/** JSON written by the Export button. */
export function exportParams(p: EditableParams): string {
    return JSON.stringify({ ...p, _comment: COMMENT }, null, 2) + "\n";
}

