/**
 * Modèle du params.json édité dans le navigateur : template neutre, fusion d'un
 * fichier importé, textes d'aide. Les listes (stats, traits, signes, réglages
 * par défaut) viennent du moteur → une seule source de vérité.
 */

import { ALL_STATS, ALL_TRAITS } from "../src/config/constants";
import { ALL_SIGNS } from "../src/config/signs";
import { DEFAULT_SETTINGS, Settings } from "../src/config/settings";
import type { RoleName } from "../src/types";

export const ROLES: RoleName[] = ["setter", "outsideHitter", "middleBlocker", "oppositeHitter", "libero"];

export const ROLE_TITLES: Record<RoleName, string> = {
    setter: "Setter",
    outsideHitter: "Outside Hitter",
    middleBlocker: "Middle Blocker",
    oppositeHitter: "Opposite",
    libero: "Libero",
};

export interface RoleParams {
    statsWeights: Record<string, number>;
    traitBonuses: Record<string, number>;
    signBonuses: Record<string, number>;
}

export interface EditableParams {
    _comment?: string;
    traitWeight: number;
    settings: Settings;
    roles: Record<RoleName, RoleParams>;
}

export const STATS = ALL_STATS;
export const TRAITS = ALL_TRAITS;
export const SIGNS = ALL_SIGNS as string[];

/** Ranges of the editor controls. */
export const RANGES = {
    stat: { min: 0, max: 10, step: 1 },
    trait: { min: -10, max: 15, step: 0.5 },
    sign: { min: 0, max: 10, step: 0.5 },
};

const COMMENT =
    "World Aces roster analyst parameters — generated by the web editor. " +
    "statsWeights: 0-10 per sub-stat (normalised, only ratios matter). " +
    "traitBonuses / signBonuses: points added to the 0-99 stat score. " +
    "traitWeight multiplies every traitBonus. settings: thresholds of the analysis.";

const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v)) as T;

/**
 * Neutral starting point: every stat counts the same, no trait / sign bonus.
 * It is deliberately NOT a tuned profile — each manager builds their own.
 */
export function neutralParams(): EditableParams {
    const roles = {} as Record<RoleName, RoleParams>;
    for (const r of ROLES) {
        roles[r] = {
            statsWeights: Object.fromEntries(STATS.map((s) => [s, 5])),
            traitBonuses: Object.fromEntries(TRAITS.map((t) => [t, 0])),
            signBonuses: Object.fromEntries(SIGNS.map((s) => [s, 0])),
        };
    }
    return { _comment: COMMENT, traitWeight: 1, settings: clone(DEFAULT_SETTINGS), roles };
}

const isObj = (v: unknown): v is Record<string, unknown> =>
    typeof v === "object" && v !== null && !Array.isArray(v);

/** Deep merge of known keys only (same type as the template). */
function mergeKnown(base: Record<string, unknown>, src: unknown, freeKeys: Set<string>, path = "", notes: string[] = []): string[] {
    if (!isObj(src)) return notes;
    for (const [k, v] of Object.entries(src)) {
        const p = path ? `${path}.${k}` : k;
        if (k.startsWith("_")) continue;
        if (!(k in base)) { notes.push(`unknown key "${p}" ignored`); continue; }
        const cur = base[k];
        if (freeKeys.has(p)) {
            if (isObj(v)) base[k] = clone(v);
        } else if (isObj(cur)) {
            mergeKnown(cur, v, freeKeys, p, notes);
        } else if (Array.isArray(cur)) {
            if (Array.isArray(v)) base[k] = clone(v);
            else notes.push(`"${p}" should be a list — default kept`);
        } else if (typeof v === typeof cur) {
            base[k] = v;
        } else {
            notes.push(`"${p}" should be a ${typeof cur} — default kept`);
        }
    }
    return notes;
}

/**
 * Loads an existing params.json on top of the neutral template. Missing values
 * keep their neutral default; unknown keys are reported.
 */
export function importParams(raw: unknown): { params: EditableParams; notes: string[] } {
    if (!isObj(raw)) throw new Error("not a JSON object");
    if (!isObj(raw.roles)) throw new Error('missing "roles" block');
    const p = neutralParams();
    const notes: string[] = [];
    if (typeof raw.traitWeight === "number") p.traitWeight = raw.traitWeight;
    mergeKnown(p.settings as unknown as Record<string, unknown>, raw.settings, new Set([
        "settings.roster.targetCounts", "settings.recruitment.singletonTraitPositions",
    ]), "settings", notes);
    for (const [role, cfg] of Object.entries(raw.roles)) {
        if (!(ROLES as string[]).includes(role)) { notes.push(`unknown role "${role}" ignored`); continue; }
        mergeKnown(p.roles[role as RoleName] as unknown as Record<string, unknown>, cfg, new Set(), `roles.${role}`, notes);
    }
    return { params: p, notes };
}

/** JSON written by the Export button. */
export function exportParams(p: EditableParams): string {
    return JSON.stringify({ ...p, _comment: COMMENT }, null, 2) + "\n";
}

